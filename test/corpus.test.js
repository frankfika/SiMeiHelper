let posPass = 0, posFail = 0, negPass = 0, negFail = 0
let dgPass = 0, dgFail = 0, dsPass = 0, dsFail = 0
const fails = []

function check(actual, expected, text, kind) {
  const ok = actual === expected
  if (ok) {
    if (kind === 'pos') posPass++; else if (kind === 'neg') negPass++
    else if (kind === 'dg') dgPass++; else dsPass++
  } else {
    if (kind === 'pos') posFail++; else if (kind === 'neg') negFail++
    else if (kind === 'dg') dgFail++; else dsFail++
    fails.push({ text, expected, actual, kind })
  }
}

